using System;
using System.IO;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace RemappingTime.EditorTools
{
    /// <summary>
    /// One-click Android build of the demo scene: <b>Remapping Time → Build APK</b>.
    /// Output: <c>Builds/RemappingTime.apk</c>. Install with <c>adb install -r Builds/RemappingTime.apk</c>.
    /// Batch mode: <c>-executeMethod RemappingTime.EditorTools.DemoBuild.BuildFromCommandLine</c>.
    /// </summary>
    public static class DemoBuild
    {
        public const string OutputPath = "Builds/RemappingTime.apk";

        [MenuItem("Remapping Time/Build APK", priority = 20)]
        public static void BuildMenu()
        {
            BuildReport report = Build();
            EditorUtility.DisplayDialog("Remapping Time",
                report.summary.result == BuildResult.Succeeded
                    ? $"Built {OutputPath} ({report.summary.totalSize / (1024 * 1024)} MB)."
                    : $"Build {report.summary.result}. See the Console for details.", "OK");
        }

        public static void BuildFromCommandLine()
        {
            try
            {
                BuildReport report = Build();
                EditorApplication.Exit(report.summary.result == BuildResult.Succeeded ? 0 : 1);
            }
            catch (Exception e)
            {
                Debug.LogException(e);
                EditorApplication.Exit(1);
            }
        }

        public static BuildReport Build()
        {
            if (!File.Exists(DemoSceneBuilder.ScenePath) || !SceneIsComplete())
            {
                Debug.LogWarning("[RemappingTime] Demo scene is missing or outdated (a component was added since it was generated); regenerating it.");
                DemoSceneBuilder.Build();
            }
            Directory.CreateDirectory(Path.GetDirectoryName(OutputPath));

            var options = new BuildPlayerOptions
            {
                scenes = new[] { DemoSceneBuilder.ScenePath },
                locationPathName = OutputPath,
                target = BuildTarget.Android,
                targetGroup = BuildTargetGroup.Android,
                options = BuildOptions.None,
            };
            BuildReport report = BuildPipeline.BuildPlayer(options);
            Debug.Log($"[RemappingTime] Build {report.summary.result}: {OutputPath}, {report.summary.totalErrors} errors, " +
                      $"{report.summary.totalWarnings} warnings, {report.summary.totalTime}.");
            return report;
        }

        /// <summary>Components every generated demo scene must contain, by script GUID.</summary>
        private static readonly Type[] RequiredComponents =
        {
            typeof(TimeRemapEngine), typeof(StereoPassthroughCapture), typeof(ReprojectedFrameView),
            typeof(HeadsetHud), typeof(ZoneVolume), typeof(DepthProbe), typeof(Remote.RemoteControlBridge),
        };

        /// <summary>
        /// Checks the saved scene file for every required component (by script GUID), without opening it.
        /// Catches scenes generated by an older version of the builder.
        /// </summary>
        private static bool SceneIsComplete()
        {
            string yaml = File.ReadAllText(DemoSceneBuilder.ScenePath);
            if (!yaml.Contains(DemoSceneBuilder.RootName))
            {
                Debug.Log($"[RemappingTime] Scene was made by an older builder (expected '{DemoSceneBuilder.RootName}').");
                return false;
            }
            foreach (Type t in RequiredComponents)
            {
                string[] guids = AssetDatabase.FindAssets($"{t.Name} t:MonoScript");
                bool found = false;
                foreach (string guid in guids)
                {
                    var script = AssetDatabase.LoadAssetAtPath<MonoScript>(AssetDatabase.GUIDToAssetPath(guid));
                    if (script != null && script.GetClass() == t && yaml.Contains(guid)) { found = true; break; }
                }
                if (!found) { Debug.Log($"[RemappingTime] Scene lacks {t.Name}."); return false; }
            }
            return true;
        }
    }
}
